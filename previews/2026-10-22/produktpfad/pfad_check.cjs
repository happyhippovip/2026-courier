const { chromium } = require("playwright");
const base = "http://127.0.0.1:8766/";
const shots = process.argv[2];
(async () => {
  const b = await chromium.launch();
  const out = []; const errs = [];
  const t0 = Date.now();
  const p = await b.newPage({ viewport: { width: 1280, height: 860 } });
  p.on("pageerror", (e) => errs.push(String(e)));
  await p.goto(base); await p.waitForSelector('#truth[data-mode="replay"]');
  out.push(["truth", await p.textContent("#truth")]);
  await p.screenshot({ path: `${shots}/1_start.png` });
  await p.click('#s1 [data-go="2"]'); await p.click("#run");
  await p.waitForSelector("#to3:not([hidden])", { timeout: 10000 });
  out.push(["timeline", await p.$$eval("#timeline li", (l) => l.length), await p.$$eval("#timeline li.ok", (l) => l.length)]);
  await p.screenshot({ path: `${shots}/2_mission.png` });
  await p.click("#to3"); out.push(["status3", await p.textContent("#r-status")]);
  await p.screenshot({ path: `${shots}/3_ergebnis.png` });
  await p.click('#s3 [data-go="4"]'); await p.click("#selfcheck");
  await p.waitForFunction(() => document.querySelector("#selfcheck-out").textContent.length > 0);
  out.push(["selfcheck", await p.textContent("#selfcheck-out")]);
  out.push(["checks_ok", await p.$$eval("#checks li.ok", (l) => l.length)]);
  const [dl] = await Promise.all([p.waitForEvent("download"), p.click("#receipt")]);
  const rc = JSON.parse(require("fs").readFileSync(await dl.path(), "utf8"));
  out.push(["receipt", rc.proven, rc.journal_event, rc.artifact_sha256]);
  await p.screenshot({ path: `${shots}/4_nachweis.png`, fullPage: true });
  await p.click('#s4 [data-go="5"]');
  out.push(["mailto", (await p.getAttribute("#mail", "href")).slice(0, 80)]);
  await p.screenshot({ path: `${shots}/5_pilot.png` });
  out.push(["clicks_to_contact_ms", Date.now() - t0]);
  await p.selectOption("#mode", "live"); await p.waitForSelector('#truth[data-mode="unknown"]');
  out.push(["live_without_hub", await p.textContent("#truth"), await p.textContent("#r-status")]);
  // Negative: manipulated replay (verifier did not accept) must never be green.
  const n = await b.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: "reduce" });
  await n.route("**/mission_replay.json", async (r) => {
    const resp = await r.fetch(); const d = await resp.json();
    d.verifier_result.accepted = false; d.events_replay = d.events_replay.filter((e) => e.type !== "RESULT_ACCEPTED");
    r.fulfill({ response: resp, json: d });
  });
  await n.goto(base); await n.waitForSelector('#truth[data-mode="replay"]');
  await n.click('#s1 [data-go="2"]'); await n.click("#run"); await n.click("#to3");
  out.push(["neg_status", await n.textContent("#r-status")]);
  await n.click('#s3 [data-go="4"]');
  out.push(["neg_checks_ok", await n.$$eval("#checks li.ok", (l) => l.length), await n.textContent("#p-journal")]);
  await n.screenshot({ path: `${shots}/6_negativ_mobil.png`, fullPage: true });
  const m = await b.newPage({ viewport: { width: 390, height: 844 }, colorScheme: "dark" });
  await m.goto(base); await m.waitForSelector('#truth[data-mode="replay"]');
  out.push(["mobile_hscroll", await m.evaluate(() => document.documentElement.scrollWidth > innerWidth)]);
  await m.screenshot({ path: `${shots}/7_start_mobil_dunkel.png` });
  out.push(["pageerrors", errs.length]);
  console.log(JSON.stringify(out, null, 1));
  await b.close();
})();
