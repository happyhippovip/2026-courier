// pgvector-local-kit — Schema Extractor & DDL Converter
// Translates cloud PostgreSQL / Supabase schema definitions into local PostgreSQL with pgvector.
// Zero external dependencies.

class SchemaExtractor {
  constructor() {
    this.vectorColumns = [];
    this.tables = [];
    this.indexes = [];
  }

  parseDDL(ddlSql) {
    if (typeof ddlSql !== 'string' || !ddlSql.trim()) {
      throw new Error('[SCHEMA_EXTRACTOR_ERROR] Input DDL must be a non-empty string');
    }

    this.vectorColumns = [];
    this.tables = [];
    this.indexes = [];

    const cleaned = ddlSql
      .replace(/--.*$/gm, '')
      .replace(/\/\*[\s\S]*?\*\//g, '');

    const tableRegex = /CREATE\s+TABLE(?:\s+IF\s+NOT\s+EXISTS)?\s+([^\s(]+)\s*\(([\s\S]*?)\);/gi;
    let tableMatch;
    while ((tableMatch = tableRegex.exec(cleaned)) !== null) {
      const tableName = tableMatch[1].replace(/["`]/g, '').trim();
      const body = tableMatch[2];
      const columns = [];

      const colLines = body.split(',\n').map(c => c.trim()).filter(Boolean);
      for (const line of colLines) {
        const colMatch = line.match(/^([^\s]+)\s+([^\s,()]+(?:\([^)]+\))?)/);
        if (colMatch) {
          const colName = colMatch[1].replace(/["`]/g, '');
          const colType = colMatch[2].toLowerCase();

          const vectorMatch = colType.match(/^vector\((\d+)\)$/);
          if (vectorMatch) {
            const dimensions = parseInt(vectorMatch[1], 10);
            this.vectorColumns.push({
              table: tableName,
              column: colName,
              dimensions
            });
          }

          columns.push({
            name: colName,
            type: colType,
            raw: line.trim()
          });
        }
      }

      this.tables.push({
        name: tableName,
        columns
      });
    }

    const indexRegex = /CREATE\s+INDEX(?:\s+IF\s+NOT\s+EXISTS)?\s+([^\s]+)\s+ON\s+([^\s(]+)\s+USING\s+(hnsw|ivfflat)\s*\(([^\s(]+(?:\s+[^)]+)?)\)(?:\s+WITH\s*\(([^\s(]+=[^)]+)\))?;/gi;
    let indexMatch;
    while ((indexMatch = indexRegex.exec(cleaned)) !== null) {
      const indexName = indexMatch[1].replace(/["`]/g, '').trim();
      const tableName = indexMatch[2].replace(/["`]/g, '').trim();
      const indexMethod = indexMatch[3].toLowerCase();
      const columnExpr = indexMatch[4].trim();
      const withParams = indexMatch[5] ? indexMatch[5].trim() : null;

      this.indexes.push({
        name: indexName,
        table: tableName,
        method: indexMethod,
        columnExpr,
        params: withParams
      });
    }

    return {
      tableCount: this.tables.length,
      tables: this.tables,
      vectorColumnCount: this.vectorColumns.length,
      vectorColumns: this.vectorColumns,
      indexCount: this.indexes.length,
      indexes: this.indexes
    };
  }

  generateLocalDDL(localDbName = 'local_agent_db') {
    const lines = [];
    lines.push('-- ==========================================================');
    lines.push(`-- LOCAL PGVECTOR SCHEMA — Target DB: ${localDbName}`);
    lines.push('-- Generated by pgvector-local-kit v1.0.0 (Zero-Egress Mode)');
    lines.push('-- ==========================================================');
    lines.push('');
    lines.push('-- 1. Enable Required Extensions');
    lines.push('CREATE EXTENSION IF NOT EXISTS "uuid-ossp";');
    lines.push('CREATE EXTENSION IF NOT EXISTS "vector";');
    lines.push('');

    lines.push('-- 2. Core Tables');
    for (const tbl of this.tables) {
      lines.push(`CREATE TABLE IF NOT EXISTS ${tbl.name} (`);
      const colDefs = tbl.columns.map(c => `  ${c.raw}`);
      lines.push(colDefs.join(',\n'));
      lines.push(');');
      lines.push('');
    }

    if (this.indexes.length > 0) {
      lines.push('-- 3. Vector & Performance Indexes');
      for (const idx of this.indexes) {
        let stmt = `CREATE INDEX IF NOT EXISTS ${idx.name} ON ${idx.table} USING ${idx.method} (${idx.columnExpr})`;
        if (idx.params) {
          stmt += ` WITH (${idx.params})`;
        }
        stmt += ';';
        lines.push(stmt);
      }
      lines.push('');
    }

    return lines.join('\n');
  }
}

module.exports = { SchemaExtractor };
