"""Pipeline Orchestrator for Real A to B to C Handoffs.

Orchestrates the canonical chain:
DISPATCH -> WORKER A -> HANDOFF -> WORKER B -> VERIFIER -> DONE
Enforcing cryptographic stage receipts, handoff validation, and independent
verifier gating before declaring any task final.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any, Callable, Sequence

from courier_core.receipt_signer import ReceiptSigner, SignedReceipt


def _hash_payload(obj: Any) -> str:
    raw = json.dumps(obj, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()


@dataclass
class StageReceipt:
    """Cryptographic evidence generated by a specific pipeline stage."""

    stage: str
    item_id: str
    payload: dict[str, Any]
    signature: str
    signed_at: str

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class PipelineResult:
    """End-to-end outcome of an A -> B -> C pipeline execution."""

    status: str
    item_id: str
    is_verified: bool
    stage_receipts: dict[str, StageReceipt] = field(default_factory=dict)
    error_message: str = ""

    def get_aggregated_evidence(self) -> dict[str, str]:
        evidence: dict[str, str] = {}
        for stage_name, receipt in self.stage_receipts.items():
            evidence[f"{stage_name}_hash"] = _hash_payload(receipt.payload.get("output", receipt.payload))
        return evidence

    def to_dict(self) -> dict[str, Any]:
        return {
            "status": self.status,
            "item_id": self.item_id,
            "is_verified": self.is_verified,
            "stage_receipts": {k: v.to_dict() for k, v in self.stage_receipts.items()},
            "error_message": self.error_message,
            "evidence": self.get_aggregated_evidence(),
        }


class PipelineOrchestrator:
    """Coordinates multi-stage worker handoffs with zero synthetic success."""

    def __init__(
        self,
        secret_key: str,
        out_dir: str = "run/pipelines",
    ):
        self.secret_key = secret_key
        self.out_dir = Path(out_dir)
        self.signer = ReceiptSigner(secret_key=self.secret_key)

    def execute(
        self,
        item_id: str,
        worker_a_fn: Callable[[dict[str, Any]], dict[str, Any]],
        worker_b_fn: Callable[[dict[str, Any]], dict[str, Any]],
        verifier_fn: Callable[[dict[str, Any], dict[str, Any]], bool],
        stage_a_post_hook: Callable[[StageReceipt], None] | None = None,
    ) -> PipelineResult:
        # --- STAGE 1: WORKER A ---
        try:
            output_a = worker_a_fn({"item_id": item_id})
            if not isinstance(output_a, dict) or str(output_a.get("status", "")).upper() in (
                "FAIL", "FAILED", "ERROR", "ABORTED"
            ):
                raise RuntimeError("Worker A returned non-passing output")
            signed_a = self.signer.sign({
                "stage": "worker_a",
                "item_id": item_id,
                "output": output_a,
            })
            receipt_a = StageReceipt(
                stage="worker_a",
                item_id=item_id,
                payload=signed_a.payload,
                signature=signed_a.signature,
                signed_at=signed_a.signed_at,
            )
            if stage_a_post_hook:
                stage_a_post_hook(receipt_a)
        except Exception as exc:
            return PipelineResult(
                status="FAILED_STAGE_A",
                item_id=item_id,
                is_verified=False,
                error_message=str(exc),
            )

        # --- HANDOFF VALIDATION ---
        verif_a = self.signer.verify({
            "payload": receipt_a.payload,
            "signature": receipt_a.signature,
            "signed_at": receipt_a.signed_at,
        })
        if not verif_a.is_valid:
            return PipelineResult(
                status="HANDOFF_VERIFICATION_FAILED",
                item_id=item_id,
                is_verified=False,
                stage_receipts={"worker_a": receipt_a},
                error_message="Handoff receipt verification failed before Worker B processing",
            )

        # --- STAGE 2: WORKER B ---
        try:
            output_b = worker_b_fn(receipt_a.payload.get("output", {}))
            if not isinstance(output_b, dict) or str(output_b.get("status", "")).upper() in (
                "FAIL", "FAILED", "ERROR", "ABORTED"
            ):
                raise RuntimeError("Worker B returned non-passing output")
            signed_b = self.signer.sign({
                "stage": "worker_b",
                "item_id": item_id,
                "output": output_b,
            })
            receipt_b = StageReceipt(
                stage="worker_b",
                item_id=item_id,
                payload=signed_b.payload,
                signature=signed_b.signature,
                signed_at=signed_b.signed_at,
            )
        except Exception as exc:
            return PipelineResult(
                status="FAILED_STAGE_B",
                item_id=item_id,
                is_verified=False,
                stage_receipts={"worker_a": receipt_a},
                error_message=str(exc),
            )

        # --- STAGE 3: INDEPENDENT VERIFIER ---
        try:
            is_ok = verifier_fn(
                receipt_a.payload.get("output", {}),
                receipt_b.payload.get("output", {}),
            )
            if not is_ok:
                return PipelineResult(
                    status="VERIFICATION_FAILED",
                    item_id=item_id,
                    is_verified=False,
                    stage_receipts={"worker_a": receipt_a, "worker_b": receipt_b},
                    error_message="Verifier rejected stage artifacts",
                )

            signed_v = self.signer.sign({
                "stage": "verifier",
                "item_id": item_id,
                "output": {"verified": True},
            })
            receipt_v = StageReceipt(
                stage="verifier",
                item_id=item_id,
                payload=signed_v.payload,
                signature=signed_v.signature,
                signed_at=signed_v.signed_at,
            )
        except Exception as exc:
            return PipelineResult(
                status="VERIFICATION_FAILED",
                item_id=item_id,
                is_verified=False,
                stage_receipts={"worker_a": receipt_a, "worker_b": receipt_b},
                error_message=str(exc),
            )

        # --- FINALIZATION & RECORDING ---
        stage_receipts = {
            "worker_a": receipt_a,
            "worker_b": receipt_b,
            "verifier": receipt_v,
        }
        res = PipelineResult(
            status="DONE",
            item_id=item_id,
            is_verified=True,
            stage_receipts=stage_receipts,
        )

        self.out_dir.mkdir(parents=True, exist_ok=True)
        out_file = self.out_dir / f"pipeline_{item_id}.json"
        out_file.write_text(json.dumps(res.to_dict(), indent=2), encoding="utf-8")

        return res


def run_abc_pipeline(
    item_id: str,
    secret_key: str,
    worker_a_fn: Callable[[dict[str, Any]], dict[str, Any]],
    worker_b_fn: Callable[[dict[str, Any]], dict[str, Any]],
    verifier_fn: Callable[[dict[str, Any], dict[str, Any]], bool],
    out_dir: str = "run/pipelines",
) -> PipelineResult:
    orchestrator = PipelineOrchestrator(secret_key=secret_key, out_dir=out_dir)
    return orchestrator.execute(
        item_id=item_id,
        worker_a_fn=worker_a_fn,
        worker_b_fn=worker_b_fn,
        verifier_fn=verifier_fn,
    )


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Pipeline Orchestrator for Real A->B->C.")
    parser.add_argument("--item", required=True, help="Work item ID")
    parser.add_argument("--key", required=True, help="HMAC secret key")
    parser.add_argument("--out-dir", default="run/pipelines", help="Output directory")
    parser.add_argument("--mock-run", action="store_true", help="Run with mock A->B->Verifier workers")

    args = parser.parse_args(argv)

    if args.mock_run:
        orchestrator = PipelineOrchestrator(secret_key=args.key, out_dir=args.out_dir)
        res = orchestrator.execute(
            item_id=args.item,
            worker_a_fn=lambda inp: {"mock_a": "produced code"},
            worker_b_fn=lambda a: {"mock_b": "produced tests"},
            verifier_fn=lambda a, b: True,
        )
        print(json.dumps(res.to_dict()))
        return 0 if res.status == "DONE" else 1

    print(json.dumps({"status": "REJECTED", "error": "Real worker callbacks required unless --mock-run is set"}))
    return 2


if __name__ == "__main__":
    sys.exit(main())
